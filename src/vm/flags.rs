/// Shift kind.
#[derive(Clone, Copy, PartialEq, Eq)]
pub enum ShiftKind {
    Shl,
    Shr,
    Sar,
}

/// Flags for a 32-bit shift. CF = last bit shifted out; ZF/SF/PF from result;
/// OF is defined as 0 (x86 leaves it undefined for count != 1; we define it 0
/// and the native handler masks it out too, so both sides agree).
pub fn shift_flags(kind: ShiftKind, value: u32, count: u32, result: u32) -> u64 {
    let mut f = 0u64;
    if result == 0 {
        f |= F_ZF;
    }
    if result & 0x8000_0000 != 0 {
        f |= F_SF;
    }
    if parity8(result) {
        f |= F_PF;
    }
    if count > 0 {
        let cf = match kind {
            ShiftKind::Shl => (value >> (32 - count)) & 1,
            ShiftKind::Shr | ShiftKind::Sar => (value >> (count - 1)) & 1,
        };
        if cf != 0 {
            f |= F_CF;
        }
    }
    f
}

/// Flags for a 64-bit shift. Same convention as `shift_flags` but on 64-bit
/// operands: CF = last bit shifted out; ZF/SF/PF from the result; OF and AF
/// defined as 0 (native handler masks them out too).
pub fn shift_flags64(kind: ShiftKind, value: u64, count: u32, result: u64) -> u64 {
    let mut f = 0u64;
    if result == 0 {
        f |= F_ZF;
    }
    if result & 0x8000_0000_0000_0000 != 0 {
        f |= F_SF;
    }
    if parity8(result as u32) {
        f |= F_PF;
    }
    if count > 0 {
        let cf = match kind {
            ShiftKind::Shl => (value >> (64 - count)) & 1,
            ShiftKind::Shr | ShiftKind::Sar => (value >> (count - 1)) & 1,
        };
        if cf != 0 {
            f |= F_CF;
        }
    }
    f
}
